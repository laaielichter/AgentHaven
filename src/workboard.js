// File-based workboard: lets any agent that can read and write files join the
// board, whatever its vendor or tooling (Claude, Codex, Gemini, Copilot,
// Cursor, Aider, local models, scripts) and without MCP.
//
//   WORKBOARD.md  generated view of the board, plus an Inbox where agents
//                 write one command per line ("codex: claim task_ab12")
//   LOGBOOK.md    append-only log of everything that happened
//
// `syncOnce` reads the Inbox, applies the commands through the Store (with
// the same rules as the MCP plugin and the dashboard), and writes a fresh
// WORKBOARD.md with the results. `watch` keeps doing that.
