function writeAtomic(file, text) {
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, file);
}

const readOr = (file) => { try { return fs.readFileSync(file, 'utf8'); } catch (err) { if (err.code === 'ENOENT') return null; throw err; } };

function appendLogbook(store, dir) {
  const file = path.join(dir, LOGBOOK);
  const settings = store.getSettings();
  let since = settings.logbookSeq || 0;
  try { // create it only when missing ("wx" fails if it exists), then start from the beginning
    fs.writeFileSync(file, `# Logbook — ${store.workspace}\n\nAppend-only record of the shared board, written by AgentHaven. Newest at the bottom.\n\n`, { flag: 'wx' });
    since = 0;
  } catch (err) { if (err.code !== 'EEXIST') throw err; }
  const { events, latest } = store.events({ since, limit: 500 });
  if (!events.length) return 0;
  const text = events.map((e) => {
    const d = e.detail == null ? '' : typeof e.detail === 'string' ? e.detail : e.detail.summary || e.detail.message || e.detail.to || '';
    return `- ${short(e.at)} · **${e.actor}** · ${e.action.replace(/^task\./, '')} ${e.ref ? `\`${e.ref}\`` : ''}${d ? ` — ${cell(d).slice(0, 300)}` : ''}\n`;
  }).join('');
  fs.appendFileSync(file, text);
  store.setSettings({ logbookSeq: events[events.length - 1].seq || latest }, 'agenthaven');
  return events.length;
}

// One round: read the Inbox, apply it, rewrite the board, append the logbook.
function syncOnce(store, dir) {
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, BOARD);
  const before = readOr(file);
  const lines = before ? inboxLines(before) : [];
  const results = [];
  // The command line is echoed back under "Inbox results": never echo a secret.
  for (const l of lines) results.push({ line: inspect(l).text, at: new Date().toISOString(), ...applyCommand(store, l) });
  const settings = store.getSettings();
  const kept = [...results.reverse(), ...(settings.workboardResults || [])].slice(0, MAX_RESULTS);
  if (results.length) store.setSettings({ workboardResults: kept }, 'agenthaven');
  // Lines an agent added while we were working stay in the Inbox for the next round.
  const now = readOr(file);
  const pending = now && now !== before ? inboxLines(now) : [];
  for (const l of lines) { const i = pending.indexOf(l); if (i >= 0) pending.splice(i, 1); }
  const text = renderBoard(store, { results: kept }) + (pending.length ? `${pending.join('\n')}\n` : '');
  if (text.replace(/^> Updated .*$/m, '') !== (now || '').replace(/^> Updated .*$/m, '')) writeAtomic(file, text);
  const logged = appendLogbook(store, dir);
  return { applied: results.length, results: results.reverse(), pending: pending.length, logged, file };
}

// Keeps the folder in sync: on Inbox edits, on board changes, and every 30 s.
function watch(store, dir, { interval = 1500, onSync, onError } = {}) {
  let last = '';
  let lastFull = 0;
  let busy = false;
  const tick = () => {
    if (busy) return;
    busy = true;
    try {
      const board = readOr(path.join(dir, BOARD)) || '';
      const sig = `${store.stats().seq}:${inboxLines(board).join('\n')}:${board.length}`;
      if (sig !== last || Date.now() - lastFull > 30000) {
        const r = syncOnce(store, dir);
        lastFull = Date.now();
        last = `${store.stats().seq}:${inboxLines(readOr(path.join(dir, BOARD)) || '').join('\n')}:${(readOr(path.join(dir, BOARD)) || '').length}`;
        if (onSync && (r.applied || r.logged)) onSync(r);
      }
    } catch (err) { if (onError) onError(err); } finally { busy = false; }
  };
  tick();
  const timer = setInterval(tick, interval);
  timer.unref?.();
  return { stop: () => clearInterval(timer), tick };
}

// Instructions an agent of any vendor can put in AGENTS.md, CLAUDE.md, GEMINI.md, .cursorrules, copilot-instructions.md, …
function agentInstructions(dir) {
  return `## Shared workboard (AgentHaven)

This project has one shared board for all agents and people: \`${path.join(dir, BOARD)}\`.

- Read it before you start. Work only on a task you have claimed, and never edit files listed under "Files in use" for another agent.
- To act, add one line at the very bottom of the file, under "## Inbox": \`yourname: command\`, for example \`codex: next\`, \`codex: progress task_3f9a 50% tests pass\`, \`codex: done task_3f9a added retry with tests\`. Use the same name every time.
- Re-read the file a few seconds later: the result appears under "Inbox results".
- Report progress at least every 30 minutes, or your claim expires. Finish with \`done\` or \`handoff\` and say what is next.
- If you have the AgentHaven MCP plugin, use its tools instead; they do the same thing.
`;
}

