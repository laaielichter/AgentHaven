// ---- rendering ---------------------------------------------------------------

function renderBoard(store, { results = [] } = {}) {
  const tasks = store.listTasks();
  const stats = store.stats();
  const agents = store.listAgents();
  const claims = store.fileClaims();
  const ref = (t) => `\`${t.id}\``;
  const by = (status) => tasks.filter((t) => t.status === status).sort((a, b) => a.priority - b.priority || a.createdAt.localeCompare(b.createdAt));
  const out = [];
  const line = (s = '') => out.push(s);

  line(`# Workboard — ${store.workspace}`);
  line();
  line('> One board for every agent and every person on this project, whatever the vendor: Claude, Codex, Gemini, Copilot, Cursor, local models and scripts.');
  line(`> Generated by AgentHaven ${pkg.version}. **Do not edit above the Inbox**: it is rewritten. Write commands in the Inbox at the bottom.`);
  if (stats.goal) line(`> **Goal:** ${cell(stats.goal.text)}${stats.goal.doneWhen ? ` — **done when:** ${cell(stats.goal.doneWhen)}` : ''}`);
  if (stats.complete) line('> ✅ **Every task is done.** If the goal is reached, stop. Otherwise add the tasks that are still missing.');
  line(`> ${stats.agentsOnly ? 'Agents-only mode' : 'Humans in the loop'} · lead: ${stats.lead || 'none'}${stats.escalated ? ` · ⚠ ${stats.escalated} escalated` : ''}${stats.openQuestions ? ` · ❓ ${stats.openQuestions} open question(s)` : ''}`);
  line(`> Updated ${short(new Date().toISOString())} · ${stats.counts.doing} doing · ${stats.counts.todo} to do · ${stats.counts.review} in review · ${stats.counts.blocked} blocked · ${stats.counts.done} done · ${stats.online}/${stats.agents} agents online · ${money(stats.usage.costUsd)} · ${kTokens(stats.usage.tokens)} tokens`);
  line();
  line('## How to work here');
  line();
  line('0. Start every session with `yourname: inbox`: messages, questions and reviews for you.');
  line('1. Introduce yourself once in the Inbox: `yourname: hello kind=llm vendor=... model=... skills=...`. Use the same name every time.');
  line('2. Take work with `yourname: next` (the most important task you can start) or `yourname: claim <task>`. Never work on a task you have not claimed.');
  line('3. Check **Files in use** before you edit. Never edit a file another agent has claimed. Re-read a file right before you overwrite it: someone may have changed it.');
  line('4. Report `progress` at least every 30 minutes, or your claim expires and the task goes back on the board.');
  line('5. Finish with `done <task> <summary>`, or pass it on with `handoff`. Write what you did and what is next: the next agent has only this file.');
  line('6. Your command results show up under **Inbox results** within seconds. A ✗ tells you why it was refused.');
  line();
  line('<details><summary>All commands</summary>');
  line();
  for (const [cmd, what] of COMMANDS) line(`- \`yourname: ${cmd}\` — ${what}`);
  line('- `<task>` is a task id like `task_3f9a1c2b4d5e`; its first 4+ characters after `task_` are enough.');
  line();
  line('</details>');
  line();

  line('## Active claims');
  line();
  const active = tasks.filter((t) => ['doing', 'review', 'blocked'].includes(t.status) && t.assignee);
  if (!active.length) line('_Nobody is working on anything right now._');
  else {
    line('| Task | Title | Agent | Status | Progress | Files | Claim expires |');
    line('|---|---|---|---|---|---|---|');
    for (const t of active) {
      const prog = t.progress == null ? '' : `${t.progress}%${t.progressNote ? ` ${t.progressNote}` : ''}`;
      line(`| ${ref(t)} | ${cell(t.title)} | ${cell(t.assignee)} | ${t.status}${t.blockedReason ? `: ${cell(t.blockedReason)}` : ''} | ${cell(prog)} | ${cell(t.files.join(', '))} | ${t.leaseUntil ? short(t.leaseUntil) : '—'} |`);
    }
  }
  line();

  const full = store.listTasks({ full: true });
  const questions = full.flatMap((t) => t.questions.filter((q) => !q.answer).map((q) => ({ t, q })));
  if (questions.length) {
    line('## Questions waiting for an answer');
    line();
    line('Answer with `yourname: answer <task> <answer>`. The asker\'s task waits until then.');
    line();
    for (const { t, q } of questions) line(`- \`${t.id}\` ${cell(t.title)} — **${cell(q.from)}** asks ${q.to === 'anyone' ? 'anyone' : `@${cell(q.to)}`}: ${cell(q.text)}`);
    line();
  }
  const escalated = full.filter((t) => t.escalated && t.status !== 'done');
  if (escalated.length) {
    line('## Escalated');
    line();
    line('Stuck in a loop: the lead or a human decides (split, clarify, reassign), then `resolve <task> <decision>`.');
    line();
    for (const t of escalated) line(`- \`${t.id}\` ${cell(t.title)} — ⚠ ${cell(t.escalated.reason)}`);
    line();
  }

  line('## Files in use');
  line();
  if (!claims.length) line('_No files claimed._');
  for (const c of claims) line(`- \`${c.file}\` — ${c.agent} (${ref({ id: c.task })})`);
  line();

  line('## Up next');
  line();
  const todo = by('todo');
  if (!todo.length) line('_Nothing to do. Add a task with `new`._');
  for (const t of todo) {
    const bits = [`**P${t.priority}**`, cell(t.title)];
    if (t.waitingOn?.length) bits.push(`🔒 after ${t.waitingOn.map((d) => `\`${d}\``).join(', ')}`);
    if (t.skills.length) bits.push(`skills: ${t.skills.join(', ')}`);
    if (t.files.length) bits.push(`files: ${t.files.join(', ')}`);
    if (t.criteria.length) bits.push(`criteria ${t.criteria.filter((c) => c.done).length}/${t.criteria.length}`);
    if (t.review) bits.push('needs review');
    if (t.budget) bits.push(`budget ${t.budget.costUsd !== undefined ? money(t.budget.costUsd) : `${kTokens(t.budget.tokens)} tokens`}`);
    line(`- ${ref(t)} ${bits.join(' · ')}`);
    if (t.lastHandoff) line(`  - ↪ ${cell(t.lastHandoff.from)}: ${cell(t.lastHandoff.summary)}${t.lastHandoff.nextSteps ? ` — next: ${cell(t.lastHandoff.nextSteps)}` : ''}`);
    for (const [i, c] of t.criteria.entries()) line(`  - [${c.done ? 'x' : ' '}] ${i + 1}. ${cell(c.text)}`);
  }
  line();

  const review = by('review');
  if (review.length) {
    line('## Waiting for review');
    line();
    line('Review someone else\'s work with `approve <task>` or `reject <task> <what must change>`. You cannot review your own work.');
    line();
    for (const t of review) line(`- ${ref(t)} ${cell(t.title)} — by ${cell(t.assignee)}${t.criteria.length ? ` · criteria ${t.criteria.filter((c) => c.done).length}/${t.criteria.length}` : ''}`);
    line();
  }

  const lessons = store.listNotes().filter((n) => n.tags.includes('lesson')).slice(-8).reverse();
  if (lessons.length) {
    line('## Lessons learned');
    line();
    line('Mistakes made here before, found by the dreaming agent. Read the ones that touch your files or skills.');
    line();
    for (const n of lessons) {
      const scope = [...(n.scope?.files || []), ...(n.scope?.skills || []).map((s) => `skill:${s}`), ...(n.scope?.agent ? [`agent:${n.scope.agent}`] : [])];
      line(`- **${cell(n.title)}**${scope.length ? ` (${cell(scope.join(', '))})` : ''} — ${cell(n.body).slice(0, 400)}`);
    }
    line();
  }

  line('## Agents');
  line();
  if (!agents.length) line('_No agents yet. Say hello in the Inbox._');
  else {
    line('| Agent | Kind | Vendor / model | Skills | Presence | Working on |');
    line('|---|---|---|---|---|---|');
    for (const a of agents) {
      line(`| ${cell(a.name)}${a.role === 'lead' ? ' ★ lead' : ''} | ${cell(a.kind)} | ${cell([a.vendor, a.model].filter(Boolean).join(' / '))} | ${cell(a.skills.join(', '))} | ${a.presence}${a.status ? `: ${cell(a.status)}` : ''} | ${cell(a.tasks.map((t) => t.id).join(', '))} |`);
    }
  }
  line();

  const done = by('done').sort((a, b) => b.updatedAt.localeCompare(a.updatedAt)).slice(0, 10);
  if (done.length) {
    line('## Recently done');
    line();
    for (const t of done) line(`- ${ref(t)} ${cell(t.title)} — ${cell(t.reviewedBy ? `${t.assignee || t.lastActor}, reviewed by ${t.reviewedBy}` : t.assignee || t.lastActor)} · ${short(t.updatedAt)}`);
    line();
  }

  line('## Inbox results');
  line();
  if (!results.length) line('_No commands yet._');
  for (const r of results) line(`- ${r.ok ? '✓' : '✗'} \`${cell(r.line)}\` — ${cell(r.message)}`);
  line();
  line(INBOX);
  line();
  line(INBOX_HELP);
  line();
  return out.join('\n');
}

// ---- parsing ---------------------------------------------------------------

function inboxLines(text) {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  const at = lines.map((l) => l.trim()).lastIndexOf(INBOX);
  if (at < 0) return [];
  return lines.slice(at + 1).map((l) => l.trim().replace(/^[-*+]\s+/, '').replace(/^`(.*)`$/, '$1').trim())
    .filter((l) => l && !l.startsWith('<!--') && !l.startsWith('_'));
}

function resolveTask(store, ref) {
  if (!ref) throw new Error('give a task id');
  const bare = ref.replace(/^`|`$/g, '').replace(/^#/, '');
  const tasks = store.listTasks();
  const exact = tasks.find((t) => t.id === bare);
  if (exact) return exact.id;
  const hex = bare.replace(/^task_/, '').toLowerCase();
  if (hex.length < 4) throw new Error(`task ${ref}: give at least 4 characters of the id`);
  const hits = tasks.filter((t) => t.id.slice(5).startsWith(hex));
  if (hits.length !== 1) throw new Error(hits.length ? `task ${ref} is ambiguous` : `task ${ref} not found`);
  return hits[0].id;
}

// "40% message | tokens=1200 cost=0.02 loss=0.4"
function parseProgress(rest) {
  const [head, tail = ''] = rest.split('|');
  const m = head.trim().match(/^(\d+(?:\.\d+)?)%\s*(.*)$/);
  const out = { progress: m ? Number(m[1]) : undefined, message: (m ? m[2] : head).trim() || undefined, usage: {}, metrics: {} };
  for (const pair of tail.trim().split(/\s+/).filter(Boolean)) {
    const [k, v] = pair.split('=');
    const n = Number(v);
    if (!k || v === undefined || !Number.isFinite(n)) throw new Error(`"${pair}" is not key=number`);
    if (k === 'tokens') out.usage.tokens = n;
    else if (k === 'cost' || k === 'costUsd') out.usage.costUsd = n;
    else out.metrics[k] = n;
  }
  return out;
}

function parseNew(rest) {
  const opts = { criteria: [], files: [], dependsOn: [], skills: [] };
  let text = ` ${rest} `;
  const pm = text.match(/^\s*P([0-3])\s/i);
  if (pm) { opts.priority = Number(pm[1]); text = text.slice(pm[0].length - 1); }
  else if (/^\s*P[4-9]\s/i.test(text)) throw new Error('priority must be P0 (urgent) to P3 (low)');
  text = text.replace(/\[review\]/i, () => { opts.review = true; return ''; });
  text = text.replace(/\[(files|after|skills|criteria|budget):([^\]]*)\]/gi, (_all, key, value) => {
    const k = key.toLowerCase();
    const list = value.split(k === 'criteria' ? ';' : ',').map((s) => s.trim()).filter(Boolean);
    if (k === 'files') opts.files.push(...list);
    if (k === 'after') opts.dependsOn.push(...list);
    if (k === 'skills') opts.skills.push(...list);
    if (k === 'criteria') opts.criteria.push(...list);
    if (k === 'budget') opts.budget = { costUsd: Number(value.replace(/[$\s]/g, '')) };
    return '';
  });
  const unknown = text.match(/\[([A-Za-z][A-Za-z0-9_-]*):[^\]]*\]/);
  if (unknown) throw new Error(`unknown option [${unknown[1]}: ...]; use files, after, skills, criteria, budget or [review]`);
  opts.title = text.trim();
  return opts;
}

// "summary | verified: how" → [summary, how]
const splitVerified = (s) => {
  const m = s.match(/^(.*?)\s*\|\s*verified:\s*(.+)$/is);
  if (!m) throw new Error('say how you verified it: "<summary> | verified: <commands, tests and results>"');
  return [m[1].trim(), m[2].trim()];
};

const lessonHint = (store, task, actor) => {
  const l = dreams.lessonsFor(store, task, { agent: actor });
  return l.length ? `. Read first — lessons: ${l.map((x) => `"${x.title}"`).join('; ')}` : '';
};

// Applies one Inbox line. Returns { ok, message }.
function applyCommand(store, raw) {
  const m = raw.match(/^([^:\s]+)\s*:\s*(\S+)\s*(.*)$/s);
  if (!m) return { ok: false, message: 'write "yourname: command ..."' };
  const [, actor, verb, restRaw] = m;
  if (!AGENT_RE.test(actor)) return { ok: false, message: 'agent names may use letters, digits, . _ - @' };
  const rest = restRaw.trim();
  const [first = '', ...more] = rest.split(/\s+/);
  const after = rest.slice(first.length).trim();
  const task = () => resolveTask(store, first);
  try {
    switch (verb.toLowerCase()) {
      case 'hello': case 'register': {
        const fields = Object.fromEntries(rest.split(/\s+/).filter((p) => p.includes('=')).map((p) => { const i = p.indexOf('='); return [p.slice(0, i).toLowerCase(), p.slice(i + 1)]; }));
        const a = store.registerAgent({ actor, kind: fields.kind, vendor: fields.vendor, model: fields.model, skills: fields.skills ? fields.skills.split(',') : undefined });
        return { ok: true, message: `welcome ${a.name} (${a.kind}${a.vendor ? `, ${a.vendor}` : ''}). Next: \`${actor}: next\`` };
      }
      case 'alive': case 'heartbeat': {
        const r = store.heartbeat({ actor, status: rest || undefined });
        return { ok: true, message: r.renewed.length ? `renewed ${r.renewed.length} claim(s)` : 'noted' };
      }
      case 'next': {
        const r = store.nextTask({ actor, claim: true });
        if (r.task) return { ok: true, message: `claimed ${r.task.id} "${r.task.title}"${lessonHint(store, r.task, actor)}` };
        return { ok: false, message: `${r.hint}${r.skipped?.length ? ` First: ${r.skipped[0]}.` : ''}${r.reviewable?.length ? ` Reviewable: ${r.reviewable.map((t) => t.id).join(', ')}` : ''}` };
      }
      case 'claim': { const t = store.claimTask(task(), { actor }); return { ok: true, message: `claimed "${t.title}" until ${short(t.leaseUntil)}${lessonHint(store, t, actor)}` }; }
      case 'progress': {
        const id = task();
        const p = parseProgress(after);
        // A line with neither a percentage nor any | key=value metrics used to be
        // accepted with a ✓ and a "—%" result while recording nothing. Refuse it
        // with the documented syntax instead; a metrics-only report stays valid.
        if (p.progress === undefined && !Object.keys(p.usage).length && !Object.keys(p.metrics).length) {
          throw new Error('write "progress <task> 40% [message] | tokens=12000 cost=0.03"');
        }
        const r = store.reportProgress(id, { actor, ...p });
        return { ok: true, message: `${r.progress ?? '—'}%${r.status === 'blocked' ? ` — BLOCKED: ${r.blockedReason}` : ''}` };
      }
      case 'check': case 'uncheck': {
        const t = store.setCriterion(task(), { actor, criterion: more.join(' '), done: verb.toLowerCase() === 'check' });
        return { ok: true, message: `criteria ${t.criteria.filter((c) => c.done).length}/${t.criteria.length}` };
      }
      case 'done': case 'finish': {
        const id = task();
        const t = store.getTask(id);
        if (t.review && t.assignee === actor && t.status !== 'review') {
          const [summary, verification] = splitVerified(after);
          const r = checks.submit(store, id, { actor, summary: summary || 'done', verification });
          return { ok: true, message: `sent to review${r.reviewer ? ` (reviewer: ${r.reviewer})` : ''}${r.receipt ? `; checks running on ${r.receipt.sha.slice(0, 10)}` : ''}${r.scope && !r.scope.ok ? '; ⚠ scope warning, see inbox' : ''}` };
        }
        store.updateTask(id, { version: t.version, status: 'done', actor });
        if (after) store.comment(id, { actor, body: `Done: ${after}` });
        return { ok: true, message: `done "${t.title}"` };
      }
      case 'review': {
        const [summary, verification] = splitVerified(after);
        const r = checks.submit(store, task(), { actor, summary: summary || 'ready', verification });
        return { ok: true, message: `waiting for review${r.reviewer ? ` by ${r.reviewer}` : ''}${r.receipt ? `; checks running on ${r.receipt.sha.slice(0, 10)}` : ''}${r.scope && !r.scope.ok ? '; ⚠ scope warning, see inbox' : ''}` };
      }
      case 'approve': { const t = store.reviewTask(task(), { actor, approve: true, comment: after || undefined }); return { ok: true, message: `approved "${t.title}"` }; }
      case 'reject': { const t = store.reviewTask(task(), { actor, approve: false, comment: after }); return { ok: true, message: `sent back to ${t.assignee}` }; }
      case 'handoff': {
        const hm = after.match(/^->\s*(\S+)\s*(.*)$/s);
        if (!hm) throw new Error('write "handoff <task> -> <agent or board> <summary> | <next steps>"');
        const [summary, nextSteps] = hm[2].split('|').map((s) => s.trim());
        const to = hm[1].toLowerCase() === 'board' ? null : hm[1];
        store.handoff(task(), { actor, to, summary, nextSteps });
        return { ok: true, message: to ? `handed to ${to}` : 'back on the board' };
      }
      case 'release': { store.handoff(task(), { actor, to: null, summary: after || 'released' }); return { ok: true, message: 'back on the board' }; }
      case 'block': {
        const id = task();
        const t = store.getTask(id);
        store.updateTask(id, { version: t.version, status: 'blocked', blockedReason: after || 'blocked', actor });
        return { ok: true, message: 'blocked' };
      }
      case 'comment': { store.comment(task(), { actor, body: after }); return { ok: true, message: 'comment added' }; }
      case 'new': case 'add': { const t = store.createTask({ ...parseNew(rest), actor }); return { ok: true, message: `created ${t.id} (P${t.priority})` }; }
      case 'inbox': {
        const r = store.inbox({ actor });
        const bits = [
          ...r.messages.slice(-5).map((m) => `${m.from}: ${m.body}`),
          ...r.questions.slice(0, 3).map((q) => `question on ${q.task} from ${q.from}: ${q.text}`),
          ...r.answers.map((q) => `answer on ${q.task}: ${q.answer}`),
          ...r.reviews.map((t) => `review ${t.id} "${t.title}" by ${t.by}`),
          ...r.escalations.map((t) => `escalated ${t.id}: ${t.reason}`),
        ];
        return { ok: true, message: r.count ? `${r.count} item(s) — ${bits.join(' · ').slice(0, 900)}` : 'nothing new' };
      }
      case 'ask': {
        const am = after.match(/^@(\S+)\s+(.+)$/s);
        const q = store.askQuestion(task(), { actor, to: am ? am[1] : 'anyone', question: am ? am[2] : after });
        return { ok: true, message: `asked ${q.to}; the answer will show in your inbox` };
      }
      case 'answer': { const r = store.answerQuestion(task(), { actor, answer: after }); return { ok: true, message: `answered ${r.question.from}` }; }
      case 'msg': case 'message': case 'tell': {
        const mm = rest.match(/^@(\S+)\s+(.+)$/s);
        if (!mm) throw new Error('write "msg @name text" (or @humans, @everyone, @skill:x)');
        store.sendMessage({ actor, to: mm[1], body: mm[2] });
        return { ok: true, message: `sent to ${mm[1]}` };
      }
      case 'split': {
        const seq = /^seq\s+/i.test(after);
        const parts = after.replace(/^seq\s+/i, '').split(';').map((x) => x.trim()).filter(Boolean);
        const r = store.splitTask(task(), { actor, parts, sequential: seq });
        return { ok: true, message: `split into ${r.subtasks.map((c) => c.id).join(', ')}` };
      }
      case 'lead': { const r = store.takeLead({ actor }); return { ok: true, message: `${r.lead} is the lead` }; }
      case 'goal': {
        const [g, done] = rest.split(/\|\s*done when:/i).map((x) => x.trim());
        store.setGoal({ actor, text: g, doneWhen: done });
        return { ok: true, message: 'goal set' };
      }
      case 'resolve': { store.resolveEscalation(task(), { actor, note: after }); return { ok: true, message: 'escalation resolved' }; }
      case 'worktree': { const w = gitx.createWorktree(store, task(), { actor }); return { ok: true, message: `work in ${w.path} on branch ${w.branch}` }; }
      case 'scope': {
        const r = gitx.checkScope(store, task(), { actor });
        return { ok: r.ok, message: r.ok ? `${r.changed.length} changed file(s), all inside the task` : `outside the task: ${r.outOfScope.join(', ') || '—'}; held by others: ${r.foreign.map((f) => `${f.files.join(', ')} (${f.agent})`).join('; ') || '—'}` };
      }
      case 'checks': { const r = checks.startChecks(store, task(), { actor }); return { ok: true, message: `checks running on ${r.sha.slice(0, 10)}; the result comes to your inbox` }; }
      case 'radar': {
        const r = gitx.radar(store);
        return { ok: !r.conflicts.length, message: r.conflicts.length ? r.conflicts.map((c) => `${c.files.join(', ')}: ${c.a.agent} (${c.a.id}) and ${c.b.agent} (${c.b.id})`).join('; ') : r.advice };
      }
      case 'note': {
        const [title, ...body] = rest.split('|');
        store.addNote({ title: title.trim(), body: body.join('|').trim() || title.trim(), actor });
        return { ok: true, message: 'note saved' };
      }
      default: return { ok: false, message: `unknown command "${verb}"; see "All commands"` };
    }
  } catch (err) {
    return { ok: false, message: err.message };
  }
}

